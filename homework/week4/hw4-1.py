# 自訂問題：求解 x^3 - 5 = 0 (即求 5 的立方根)
f1 = lambda x: 5 / (x * x)
f2 = lambda x: x - 1 / 10 * (x**3 - 5)
f3 = lambda x: 2 / 3 * x + 5 / (3 * x * x)

# 設定初始值 x0 = 1.5
x1 = x2 = x3 = 1.5

print(f"{'Iter':<5} | {'x1 (發散)':<15} | {'x2 (慢速收斂)':<18} | {'x3 (牛頓法快速收斂)':<20}")
print("-" * 65)

for i in range(1, 11):
    x1, x2, x3 = f1(x1), f2(x2), f3(x3) # 關鍵在這裡 重複更新 x1, x2, x3 的值 
    print(f"{i:<5} | {x1:<15.6f} | {x2:<18.8f} | {x3:<20.10f}")